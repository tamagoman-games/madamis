function build(sc) {
  const map = {};
  for (const c of sc.characters) for (const k of c.clues) map[k.id] = k;
  for (const p of sc.places) map[p.clue.id] = p.clue;
  for (const key of Object.keys(sc.systemClues)) for (const k of sc.systemClues[key]) map[k.id] = k;
  sc.clueMap = map;
  return sc;
}

